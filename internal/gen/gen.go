// Package gen renders language templates from the loaded IR.
//
// Templates live in templates/<lang>/ and are embedded into the binary so
// `go install` produces a self-contained generator. A template file named
// "src__models.ts.tmpl" is written to "src/models.ts" — the double underscore
// is a path separator, which keeps the embedded FS flat while still letting a
// language target choose its own output layout.
package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"io/fs"
	"path"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"github.com/6cclab/simplefin-sdk/internal/ir"
	"github.com/6cclab/simplefin-sdk/templates"
)

const (
	pathSep    = "__"
	tmplSuffix = ".tmpl"
)

// Generated is one rendered file.
type Generated struct {
	// Path is relative to the output directory, e.g. "src/models.ts".
	Path string
	// Content is the rendered, formatted file body.
	Content []byte
}

// Templates are executed against *View (see view.go), which flattens the IR
// into exactly what each template needs so the templates stay declarative.

// Languages returns the available target languages, sorted.
func Languages() ([]string, error) {
	entries, err := fs.ReadDir(templates.FS, ".")
	if err != nil {
		return nil, fmt.Errorf("gen: reading templates: %w", err)
	}
	var langs []string
	for _, e := range entries {
		if e.IsDir() {
			langs = append(langs, e.Name())
		}
	}
	sort.Strings(langs)
	return langs, nil
}

// Generate renders every template for lang. Output is deterministic: the same
// spec and language always produce byte-identical files, which is what lets
// `simplefin-gen verify` act as a CI gate against hand-edited generated code.
func Generate(spec *ir.Spec, lang, pkg string) ([]Generated, error) {
	entries, err := fs.ReadDir(templates.FS, lang)
	if err != nil {
		return nil, fmt.Errorf("gen: unknown language %q: %w", lang, err)
	}

	ctx := BuildView(spec, lang, pkg, header(lang, spec))

	var out []Generated
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), tmplSuffix) {
			continue
		}

		raw, err := fs.ReadFile(templates.FS, path.Join(lang, e.Name()))
		if err != nil {
			return nil, fmt.Errorf("gen: reading %s: %w", e.Name(), err)
		}

		name := strings.TrimSuffix(e.Name(), tmplSuffix)
		tmpl, err := template.New(name).Funcs(funcMap()).Parse(string(raw))
		if err != nil {
			return nil, fmt.Errorf("gen: parsing %s: %w", e.Name(), err)
		}

		var buf bytes.Buffer
		if err := tmpl.Execute(&buf, ctx); err != nil {
			return nil, fmt.Errorf("gen: executing %s: %w", e.Name(), err)
		}

		rel := strings.ReplaceAll(name, pathSep, string(filepath.Separator))
		content, err := postProcess(rel, buf.Bytes())
		if err != nil {
			return nil, fmt.Errorf("gen: formatting %s: %w", rel, err)
		}

		out = append(out, Generated{Path: rel, Content: content})
	}

	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out, nil
}

// postProcess formats rendered output. Go is run through go/format so the
// templates do not have to be careful about alignment; other languages are
// emitted as written.
func postProcess(path string, body []byte) ([]byte, error) {
	if !strings.HasSuffix(path, ".go") {
		return normalizeTrailing(body), nil
	}
	formatted, err := format.Source(body)
	if err != nil {
		// Surface the unformatted source: a template bug is far easier to
		// find when the broken output is visible than from a line number
		// alone.
		return nil, fmt.Errorf("%w\n--- unformatted output ---\n%s", err, body)
	}
	return normalizeTrailing(formatted), nil
}

func normalizeTrailing(b []byte) []byte {
	return append(bytes.TrimRight(b, "\n"), '\n')
}

func header(lang string, spec *ir.Spec) string {
	line1 := "Code generated by simplefin-gen. DO NOT EDIT."
	line2 := fmt.Sprintf("Source: spec/simplefin.yaml (%s %s)",
		spec.Protocol.Name, spec.Protocol.SpecVersion)
	line3 := "Spec: " + spec.Protocol.SpecURL

	switch lang {
	case "node":
		return fmt.Sprintf("/**\n * %s\n * %s\n * %s\n */", line1, line2, line3)
	default: // Go and anything else using // comments
		return fmt.Sprintf("// %s\n// %s\n// %s", line1, line2, line3)
	}
}

func funcMap() template.FuncMap {
	return template.FuncMap{
		"goName":    GoName,
		"tsName":    TSName,
		"pascal":    PascalCase,
		"constName": ConstName,
		"goType":    goType,
		"tsType":    tsType,
		"goTag":     goTag,
		"goDoc":      goDoc,
		"tsDoc":      tsDoc,
		"tsDocBody":   tsDocBody,
		"tsDocRemark": tsDocRemark,
		"tsTypeName":   TSTypeName,
		"unknownParam": unknownParamName,
		"tsArgsFor":    TSArgsFor,
		"quote":     strconv_Quote,
		"join":      strings.Join,
		"hasPrefix": strings.HasPrefix,
		"trimSuffix": strings.TrimSuffix,
		"lower":     strings.ToLower,
		"upper":     strings.ToUpper,
		"tsUnion":   tsUnion,
		"errConst":  errConst,
	}
}
